def fetch_live_ayah(surah: int, ayah: int, edition: str = "quran-uthmani") -> Optional[Dict[str, Any]]:
    """تلاش برای دریافت زنده از API الکوثر/القرآن کلود."""
    url = f"https://api.alquran.cloud/v1/ayah/{surah}:{ayah}/{edition}"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "QuranHadithVerifier/1.0"})
        with urllib.request.urlopen(req, timeout=3) as response:
            data = json.loads(response.read().decode("utf-8"))
            if data.get("status") == "OK" and "data" in data:
                return {
                    "text": data["data"]["text"],
                    "edition": data["data"].get("edition", {}).get("identifier", edition),
                    "source_id": f"AlQuranCloud-{edition}",
                    "access_date": datetime.date.today().isoformat(),
                    "source_type": "LIVE_API",
                }
    except Exception:
        # در صورت نبود اینترنت، تایم‌اوت یا مسدودی شبکه در سندباکس، به سراغ کش کانونی می‌رویم
        pass
    return None


def search_ayah(surah: int, ayah: int, edition: str = "quran-uthmani") -> Dict[str, Any]:
    """
    بازیابی آیه با گیت‌های سخت.
    ضدباگ: B1 (بازیابی قبل از نقل)، B2 (شماره آیه کانونی)، B10 (خرابی API)
    """
    valid, msg = validate_surah_ayah(surah, ayah)
    if not valid:
        return {
            "found": False,
            "error": "INVALID_AYAH",
            "message": msg,
        }

    # ۱. تلاش برای دریافت از API زنده
    live_res = fetch_live_ayah(surah, ayah, edition)
    if live_res:
        live_res["found"] = True
        return live_res

    # ۲. fallback به کش کانونی محلی
    key = f"{surah}:{ayah}"
    if key in LOCAL_CANONICAL_QURAN:
        entry = LOCAL_CANONICAL_QURAN[key]
        return {
            "found": True,
            "text_ar": entry["text_ar"],
            "trans_fa": entry["trans_fa"],
            "surah_name": entry["surah_name"],
            "source_id": "Tanzil-Uthmani-Canonical",
            "edition": edition,
            "access_date": datetime.date.today().isoformat(),
            "source_type": "LOCAL_CANONICAL_CACHE",
            "message": "بازیابی‌شده از منبع کانونی عثمان طه (پایگاه آفلاین) ✅",
        }

    return {
        "found": False,
        "error": "NOT_IN_CACHE_AND_OFFLINE",
        "message": f"تأیید نشد ❌ — آیه {surah}:{ayah} در کش آفلاین موجود نیست و اتصال زنده به API در دسترس نبود.",
    }


def search_hadith(keyword_or_key: str, source_book: Optional[str] = None) -> Dict[str, Any]:
    """
    بازیابی حدیث شیعه از کتب معتبر.
    ضدباگ: B1 (بازیابی قبل از نقل)، B7 (فقط شیعه)، B3 (درجه‌بندی معتبر)
    """
    if source_book:
        try:
            check_shia_only(source_book)
        except SunniSourceError as e:
            return {
                "found": False,
                "error": "SUNNI_SOURCE_FORBIDDEN",
                "message": str(e),
            }

    # جست‌وجو در پایگاه کانونی احادیث شیعه
    clean_k = keyword_or_key.strip().lower()
    for key, data in LOCAL_CANONICAL_HADITHS.items():
        if (
            key in clean_k
            or data["title"] in clean_k
            or clean_k in data["title"]
            or clean_k in data["text_ar"]
            or clean_k in data["trans_fa"]
        ):
            return {
                "found": True,
                "data": data,
                "source_id": f"Thaqalayn-{data['book']}",
                "access_date": datetime.date.today().isoformat(),
                "source_type": "LOCAL_CANONICAL_SHIA_HADITH",
                "message": f"بازیابی‌شده از {data['book']} با سند و درجه‌بندی رجالی ✅",
            }

    return {
        "found": False,
        "error": "HADITH_NOT_FOUND",
        "message": "تأیید نشد ❌ — حدیث در منابع شیعه معتبر یافت نشد (احتمال نقل به معنا، ضعف شدید یا انتساب غیرمستند).",
    }


